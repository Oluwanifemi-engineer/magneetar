# ─── Offline Queue ───────────────────────────────────────────────────────────


@router.post("/api/device/offline-queue")
async def upload_offline_queue(
    queue: OfflineQueueUpload,
    db: sqlite3.Connection = Depends(get_db),
    device_id: str = Depends(get_current_device_or_key),
):
    """Batch upload of queued telemetry pings."""
    processed = 0
    last_armed = None

    for ping in queue.pings:
        if ping.device_id != device_id:
            continue

        now = datetime.now(timezone.utc).isoformat()
        ts = ping.device_timestamp or now

        history = db.execute(
            "SELECT * FROM locations WHERE device_id=? ORDER BY server_timestamp DESC LIMIT 10",
            (device_id,),
        ).fetchall()
        history_dicts = [dict(h) for h in history]
        score, threat_level, anomalies = sentinel.compute_score(ping, history_dicts)

        db.execute(
            """INSERT INTO locations (device_id, lat, lng, altitude, accuracy_horizontal,
               confidence_level, speed, bearing, activity_type, provider,
               battery_percent, is_charging, network_type, sentinel_score,
               threat_level, anomalies, device_timestamp, server_timestamp, was_queued,
               queued_at, queue_position, ping_sequence)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (
                device_id,
                ping.lat,
                ping.lng,
                ping.altitude,
                ping.accuracy_horizontal,
                ping.confidence_level,
                ping.speed,
                ping.bearing,
                ping.activity_type,
                ping.provider,
                ping.battery_percent,
                ping.is_charging,
                ping.network_type,
                score,
                threat_level,
                json.dumps(anomalies or []),
                ts,
                now,
                True,
                ping.queued_at,
                ping.queue_position,
                ping.ping_sequence,
            ),
        )
        last_armed = ping.capture_armed
        processed += 1

    # Same COALESCE keep-last-state semantics as the live telemetry path: a
    # queued ping's capture_armed is persisted when present, and a None (old
    # build) never wipes a previously reported state.
    db.execute(
        "UPDATE devices SET last_seen=?, capture_armed=COALESCE(?, capture_armed) WHERE id=?",
        (datetime.now(timezone.utc).isoformat(), last_armed, device_id),
    )
    db.commit()

    return {"status": "ok", "processed": processed}


# ─── FCM Token Registration ─────────────────────────────────────────────────


class FCMTokenRequest(BaseModel):
    fcm_token: str
    device_id: str = ""
    platform: Optional[str] = "android"


@router.post("/api/device/fcm-token")
async def register_fcm_token(
    req: FCMTokenRequest,
    db: sqlite3.Connection = Depends(get_db),
    resolved_device_id: str = Depends(get_current_device_or_key),
):
    """Register an FCM push notification token for a device.

    Security (F-06): this endpoint must never create device rows. The old
    code inserted a placeholder device (fingerprint='fcm_*') for ANY
    device_id, so anyone could pollute the devices table — and the shared
    API key (public, embedded in every APK) let anyone do it with an
    arbitrary id. The device must ALREADY be registered: real devices
    authenticate with their per-device key/JWT (resolved_device_id is then
    their real id), and the fcm_tokens.device_id FK enforces existence.
    """
    now = datetime.now(timezone.utc).isoformat()

    device_id = resolved_device_id

    # The shared API key (embedded in every APK — public) has NO principal, so
    # it must not be able to attach a push token to an arbitrary device:
    # with the old fallback, anyone with the key could register their own FCM
    # token under a victim's EXISTING device_id and receive the victim's theft
    # alerts (push hijacking). The only non-device id still accepted is the
    # fixed 'broadcast' relay constant, which the alert engine uses to fan out
    # to tokens registered without a device (kept for backward compat).
    if device_id == "api_key_user" or not device_id:
        requested = req.device_id.strip() if req.device_id else ""
        if requested != "broadcast":
            raise HTTPException(status_code=401, detail="Device authorization required")
        device_id = "broadcast"

    # A device that isn't registered yet must reject the token registration
    # (the app registers the device before sending its FCM token). The
    # legacy 'broadcast' relay is the one allowed non-device id — it is a
    # fixed constant, not attacker-controlled.
    if device_id != "broadcast":
        existing = db.execute("SELECT id FROM devices WHERE id=?", (device_id,)).fetchone()
        if not existing:
            raise HTTPException(status_code=401, detail="Device not registered")

    db.execute(
        """INSERT INTO fcm_tokens (device_id, fcm_token, platform, updated_at)
           VALUES (?, ?, ?, ?)
           ON CONFLICT(device_id, fcm_token) DO UPDATE SET updated_at=?""",
        (device_id, req.fcm_token, req.platform, now, now),
    )
    db.commit()

    logger.info(
        "FCM token registered",
        extra={"extra_data": {"device_id": device_id, "platform": req.platform}},
    )

    return {"status": "ok", "message": "FCM token registered", "device_id": device_id}
