def _user_exists(db, user_id: str) -> bool:
    """True when the user account actually exists in the users table."""
    return bool(db.execute("SELECT 1 FROM users WHERE id=?", (user_id,)).fetchone())


def _user_id_from_credentials(
    credentials: Optional[HTTPAuthorizationCredentials],
) -> Optional[str]:
    """Resolve a user id from an optional bearer token, if it is a user token.

    Returns None when the header is absent, unparseable, or not a user token
    (e.g. a device token). Callers treat None as "no account linking".
    """
    if not credentials or not credentials.credentials:
        return None
    try:
        payload = decode_token(credentials.credentials)
    except HTTPException:
        return None
    return user_id_from_subject(payload.get("sub", ""))


@router.post("/api/device/register")
async def register_device(
    reg: DeviceRegistration,
    db: sqlite3.Connection = Depends(get_db),
    x_api_key: str = Depends(verify_api_key),
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(security),
):
    """Register a new device and get JWT tokens. Requires API key.

    If a valid user bearer token is also supplied, the device is linked to
    that account (owner_id is set) so it appears in the user's dashboard.
    """
    validate_device_id(reg.device_id)
    now = datetime.now(timezone.utc).isoformat()
    device_key_hash = None
    if reg.device_key:
        device_key_hash = hash_device_key(reg.device_key)

    owner_id = _user_id_from_credentials(credentials)

    # A stale user token (e.g. the account was permanently deleted) must not
    # re-link a device to a ghost owner — verify the account still exists.
    if owner_id and not _user_exists(db, owner_id):
        owner_id = None

    existing = db.execute(
        "SELECT id, owner_id FROM devices WHERE id=?", (reg.device_id,)
    ).fetchone()  # ── Fingerprint dedup (reinstall recovery) ────────────────────────────
    # A reinstall wipes the app's SharedPreferences, so the new install
    # generates a FRESH device_id even though it is the SAME physical phone
    # (its ANDROID_ID fingerprint is stable across reinstalls). Without this
    # step, every reinstall leaves a stale duplicate row behind. When the
    # requested id is new but a device with the same fingerprint already
    # exists and is unowned (or its owner account is gone), we adopt the
    # existing row as canonical instead of creating a duplicate — the
    # register response returns the canonical id and the app persists it.
    #
    # Staleness guard: adoption of an UNOWNED/orphaned row ONLY happens when
    # the existing row's last report is older than MT_DEVICE_ADOPT_AFTER_HOURS
    # (default 24h; a reinstall goes silent the moment the old app is
    # removed). A CONCURRENTLY-registered device that shares a fingerprint
    # must never be hijacked — emulators, test fixtures, and dual-app
    # scenarios can legitimately share a fingerprint, and those rows report
    # recently.
    #
    # SAME-OWNER exception: a row the REGISTERING USER already owns (they
    # reinstalled the app on their own phone and are linking with their
    # token) is adopted REGARDLESS of staleness — it is provably their own
    # device (owner_id matches their token), so no theft vector exists and
    # the per-user device limit is not re-charged for a reinstall.
    #
    # Security: adoption is only for UNOWNED/orphaned rows OR rows owned by
    # the SAME authenticated user. A row owned by a DIFFERENT real account is
    # never re-pointed by an anonymous reinstall (that would let a thief who
    # reinstalled the app claim the victim's device by guessing the
    # fingerprint) — those duplicates are resolved by the owner via the
    # dashboard's password-gated delete.
    canonical_id = reg.device_id
    if existing is None and reg.fingerprint:
        candidates = db.execute(
            """SELECT id, owner_id FROM devices
               WHERE device_fingerprint=? AND id != ?
               ORDER BY datetime(COALESCE(last_seen, registered)) DESC""",
            (reg.fingerprint, reg.device_id),
        ).fetchall()
        for canonical in candidates:
            canonical_owner = canonical["owner_id"]
            if owner_id and canonical_owner == owner_id:
                # Same user reinstalling their own device — adopt regardless
                # of staleness; the token already proves ownership.
                existing = canonical
                canonical_id = canonical["id"]
                break
            if canonical_owner is None or not _user_exists(db, canonical_owner):
                # Unowned/orphaned — require the silence window so a
                # concurrently-reporting device is never hijacked.
                stale = db.execute(
                    """SELECT (last_seen IS NULL OR
                               datetime(last_seen) < datetime('now', ?)) AS is_stale
                       FROM devices WHERE id=?""",
                    (f"-{settings.DEVICE_ADOPT_AFTER_HOURS} hours", canonical["id"]),
                ).fetchone()
                if stale and stale["is_stale"]:
                    existing = canonical
                    canonical_id = canonical["id"]
                    break

    # Enforce the per-user device limit when this registration links the device
    # to an account (new links only — re-registering an already-owned device is fine).
    if owner_id:
        already_owned = existing["owner_id"] if existing else None
        if already_owned and already_owned != owner_id:
            # Orphaned ownership (owner account was permanently deleted) is
            # claimable — only block when the existing owner account is real.
            if _user_exists(db, already_owned):
                raise HTTPException(status_code=403, detail="Device already linked to another account")
        if already_owned is None or not _user_exists(db, already_owned):
            _enforce_device_limit(db, owner_id)

    if existing:
        # On the ADOPTION path (fresh reinstall re-pointed at the pre-existing
        # row) the app generated a brand-new device_key, so the key hash MUST
        # be replaced — keeping the old one would lock the reinstalled app out
        # of its own device. On a plain re-register of the same id, COALESCE
        # keeps an existing key when the payload omits one.
        if canonical_id != reg.device_id and device_key_hash is not None:
            db.execute(
                """UPDATE devices
                   SET device_fingerprint=?, model=?, os_version=?,
                       app_version=?, imei_hash=?, sim_serial_hash=?,
                       device_key_hash=?, owner_id=COALESCE(?, owner_id), last_seen=?
                   WHERE id=?""",
                (
                    reg.fingerprint,
                    reg.model,
                    reg.os_version,
                    reg.app_version,
                    reg.imei_hash,
                    reg.sim_serial_hash,
                    device_key_hash,
                    owner_id,
                    now,
                    canonical_id,
                ),
            )
        else:
            db.execute(
                """UPDATE devices
                   SET device_fingerprint=?, model=?, os_version=?,
                       app_version=?, imei_hash=?, sim_serial_hash=?,
                       device_key_hash=COALESCE(?, device_key_hash),
                       owner_id=COALESCE(?, owner_id), last_seen=?
                   WHERE id=?""",
                (
                    reg.fingerprint,
                    reg.model,
                    reg.os_version,
                    reg.app_version,
                    reg.imei_hash,
                    reg.sim_serial_hash,
                    device_key_hash,
                    owner_id,
                    now,
                    canonical_id,
                ),
            )
    else:
        # Unowned-registration cap (F-07): the low-privilege DEVICE key is
        # PUBLIC (it ships inside every APK), so a new unowned device row
        # costs nothing to create — cap how many can exist so an attacker
        # can't flood the devices table with junk. Account-linked
        # registrations are bounded by the per-user device limit instead.
        # Adoption of an existing unowned row never hits this (no new row is
        # created).
        if owner_id is None:
            unowned = db.execute("SELECT COUNT(*) as cnt FROM devices WHERE owner_id IS NULL").fetchone()["cnt"]
            if unowned >= settings.MAX_UNOWNED_DEVICES:
                raise HTTPException(
                    status_code=403,
                    detail=(
                        "Too many unowned devices on this server — register the "
                        "device to your account instead (sign in on the phone first)"
                    ),
                )

        db.execute(
            """INSERT INTO devices (id, device_fingerprint, model, os_version,
               app_version, imei_hash, sim_serial_hash, device_key_hash, owner_id, last_seen, registered)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (
                canonical_id,
                reg.fingerprint,
                reg.model,
                reg.os_version,
                reg.app_version,
                reg.imei_hash,
                reg.sim_serial_hash,
                device_key_hash,
                owner_id,
                now,
                now,
            ),
        )

    # Prefill the Offline Command Relay recipient (sms_phone) from the SIM
    # number the app reports — but ONLY when sms_phone is still NULL, so an
    # owner-confirmed number is never overwritten by a later registration.
    if reg.sim_phone:
        db.execute(
            "UPDATE devices SET sms_phone=COALESCE(sms_phone, ?) WHERE id=?",
            (reg.sim_phone, canonical_id),
        )

    # Fresh registration un-archives the device (it is alive and reporting).
    unarchive_device(db, canonical_id)
    db.commit()

    # Sync the WebSocket owner cache with the ACTUAL owner after the write.
    # COALESCE keeps an existing owner on re-register, so re-read the row to
    # avoid flipping the cache to the registering user when ownership didn't
    # change (which would leak another user's broadcasts to the wrong client).
    final_owner = db.execute("SELECT owner_id FROM devices WHERE id=?", (canonical_id,)).fetchone()
    update_device_owner(canonical_id, final_owner["owner_id"] if final_owner else None)

    tokens = create_device_tokens(canonical_id)
    log_audit("device_registered", actor=canonical_id, details=reg.model)

    return {
        **tokens,
        "device_id": canonical_id,
        "has_device_key": device_key_hash is not None,
        "owner_id": final_owner["owner_id"] if final_owner else None,
        "server_time": now,
    }


def _enforce_device_limit(db, user_id: str):
    """Raise 403 when the user already owns their plan's device allowance.

    The allowance comes from the account's tier (free=1, personal=3,
    guardian=10, enterprise/admin=unlimited) — see plan_device_limit().
    """
    tier_row = db.execute("SELECT tier FROM users WHERE id=?", (user_id,)).fetchone()
    tier = tier_row["tier"] if tier_row else "free"
    limit = plan_device_limit(tier)
    count = db.execute("SELECT COUNT(*) as cnt FROM devices WHERE owner_id=?", (user_id,)).fetchone()["cnt"]
    if count >= limit:
        raise HTTPException(
            status_code=403,
            detail=f"Device limit reached ({count}/{limit}) — upgrade your plan to protect more devices",
        )


@router.post("/api/device/claim")
async def claim_device(
    req: DeviceClaimRequest,
    db: sqlite3.Connection = Depends(get_db),
    user_id: str = Depends(get_current_user),
    x_device_key: Optional[str] = Header(None),
):
    """Link an existing device to the authenticated user's account.

    The device is identified by its per-device secret key (x-device-key header)
    or, failing that, by an explicit device_id in the body. The user is
    authenticated with a user bearer token. Once linked, the device shows up
    in the user's dashboard and is scoped to their account.
    """
    if user_id == "api_key_user":
        raise HTTPException(status_code=401, detail="User authentication required")

    # A stale token from a permanently deleted account must not claim devices
    # (that would re-create a ghost link — same bug class as register).
    if not _user_exists(db, user_id):
        raise HTTPException(status_code=401, detail="Account no longer exists")

    device = None
    if x_device_key:
        key_hash = hash_device_key(x_device_key)
        device = db.execute("SELECT id, owner_id FROM devices WHERE device_key_hash=?", (key_hash,)).fetchone()
    if device is None and req.device_id:
        device = db.execute("SELECT id, owner_id FROM devices WHERE id=?", (req.device_id,)).fetchone()
    if device is None:
        raise HTTPException(status_code=404, detail="Device not found")

    existing_owner = device["owner_id"]
    # Only block cross-account claims when the existing owner is a REAL account.
    # A device whose owner account was permanently deleted (orphaned ownership,
    # e.g. after a DB restore) is claimable by anyone with the device key/id.
    if existing_owner and _user_exists(db, existing_owner) and existing_owner != user_id:
        raise HTTPException(status_code=403, detail="Device already linked to another account")

    # Enforce per-user device limit before linking — skip when the device is
    # already owned by this user so re-claims stay idempotent (same as the
    # register path, which skips the limit for same-owner re-registrations).
    if existing_owner != user_id:
        _enforce_device_limit(db, user_id)

    db.execute("UPDATE devices SET owner_id=? WHERE id=?", (user_id, device["id"]))
    db.commit()
    update_device_owner(device["id"], user_id)
    log_audit("device_claimed", actor=user_id, details=f"Device: {device['id']}")

    return {"status": "ok", "device_id": device["id"], "owner_id": user_id}


