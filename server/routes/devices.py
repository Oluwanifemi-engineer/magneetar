@router.post("/api/device/media")
async def post_media(
    report: MediaReport,
    db: sqlite3.Connection = Depends(get_db),
    device_id: str = Depends(get_current_device_or_key),
):
    """Upload media (photo/audio) from device."""
    if report.device_id != device_id:
        raise HTTPException(status_code=403, detail="Device ID mismatch")

    if not check_media_rate_limit(device_id):
        raise HTTPException(status_code=429, detail="Media upload rate limit exceeded")

    now = datetime.now(timezone.utc).isoformat()
    ts = report.timestamp or now

    # Media storage refactor (v1.4): evidence bytes go to DISK via
    # media_store.py — validated (per-type size caps + magic bytes) BEFORE
    # any decode, so an oversized or bogus payload is rejected with 413/415
    # instead of spiking memory or bloating the SQLite file. The row keeps
    # metadata + the file's SHA-256; legacy base64 stays empty for new rows.
    from media_store import MediaValidationError, save_media

    try:
        stored = save_media(device_id, report.type, report.data_b64)
    except MediaValidationError as e:
        raise HTTPException(status_code=e.status_code, detail=str(e))

    data = base64.b64decode(report.data_b64)
    sha256_hash = hashlib.sha256(data).hexdigest()

    case = db.execute(
        "SELECT id FROM evidence_cases WHERE device_id=? AND status='active' ORDER BY created_at DESC LIMIT 1",
        (device_id,),
    ).fetchone()

    case_id = case["id"] if case else None

    db.execute(
        """INSERT INTO media (device_id, type, data_b64, lat, lng, timestamp,
           evidence_case_id, sha256_hash, file_path, file_size)
           VALUES (?, ?, '', ?, ?, ?, ?, ?, ?, ?)""",
        (
            device_id,
            report.type,
            report.lat,
            report.lng,
            ts,
            case_id,
            sha256_hash,
            stored["file_path"],
            stored["file_size"],
        ),
    )
    db.commit()

    media_id = db.execute("SELECT last_insert_rowid()").fetchone()[0]

    if case_id:
        evidence_builder.add_media_to_case(case_id, report.type, report.data_b64)

    await broadcast_to_dashboards(
        {
            "type": "media",
            "data": {
                "device_id": device_id,
                "media_id": media_id,
                "type": report.type,
                "timestamp": ts,
            },
        }
    )

    return {
        "status": "ok",
        "media_id": media_id,
        "evidence_case_id": case_id,
    }


