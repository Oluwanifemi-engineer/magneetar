def location_row_exists(conn: sqlite3.Connection, device_id: str, report: TelemetryPing) -> bool:
    """True when this exact ping (device + seq + device-clock timestamp) was
    already persisted.

    At-most-once guard: OkHttp's default retryOnConnectionFailure re-sends the
    SAME body when the connection dies after the server processed it (seen
    live: a captive-portal reconnect inserted every ping twice — the server
    got the request, the response was lost, the client re-POSTed the identical
    body ~45s later). A normal (non-unique) index keeps this lookup cheap;
    the check itself is the constraint, so existing dirty rows don't block
    the migration.
    """
    if not report.ping_sequence:
        return False
    row = conn.execute(
        "SELECT 1 FROM locations WHERE device_id=? AND ping_sequence=? AND device_timestamp=? LIMIT 1",
        (device_id, report.ping_sequence, report.device_timestamp),
    ).fetchone()
    return row is not None


def _persist_location(
    conn: sqlite3.Connection,
    *,
    device_id: str,
    report: TelemetryPing,
    score: int,
    threat_level: str,
    anomalies: list,
    now: str,
    ts: str,
) -> None:
    """Insert one location row + refresh the device row.

    Shared by the synchronous path (runs on the request connection) and the
    batched path (runs on the write queue's dedicated connection). Keeping
    the SQL in one place guarantees the two paths can never drift.

    At-most-once: a retried/duplicate ping (same device + ping_sequence +
    device_timestamp) is skipped — the device row's last_seen still refreshes
    below, but no second row is inserted.
    """
    if location_row_exists(conn, device_id, report):
        return
    # At-rest encryption (v1.5): when MT_ENCRYPTION_KEY is configured, the
    # coordinates are AES-256-GCM encrypted with the per-device HKDF key — the
    # row stores 0.0 placeholders + ciphertext in location_data. Sentinel and
    # the WebSocket feed already run on the in-memory `report` payload, so
    # encrypting at the DB boundary never affects theft detection.
    lat, lng, loc_enc, loc_data = encrypt_location_for_store(report.lat, report.lng, device_id)
    conn.execute(
        """INSERT INTO locations (device_id, lat, lng, altitude, accuracy_horizontal,
           accuracy_vertical, confidence_level, speed, bearing, activity_type,
           step_count, provider, gps_satellite_count, wifi_bssids, cell_tower_ids,
           ble_devices_nearby, battery_percent, is_charging, network_type,
           signal_strength_dbm, is_location_enabled, is_airplane_mode,
           sim_changed, sim_serial_hash, sentinel_score, threat_level, anomalies,
           device_timestamp, server_timestamp, was_queued, queued_at,
           queue_position, ping_sequence, location_encrypted, location_data)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (
            device_id,
            lat,
            lng,
            report.altitude,
            report.accuracy_horizontal,
            report.accuracy_vertical,
            report.confidence_level,
            report.speed,
            report.bearing,
            report.activity_type,
            report.step_count,
            report.provider,
            report.gps_satellite_count,
            json.dumps(report.wifi_bssids or []),
            json.dumps(report.cell_tower_ids or []),
            report.ble_devices_nearby,
            report.battery_percent,
            report.is_charging,
            report.network_type,
            report.signal_strength_dbm,
            report.is_location_enabled,
            report.is_airplane_mode,
            report.sim_changed,
            report.sim_serial_hash,
            score,
            threat_level,
            json.dumps(anomalies or []),
            ts,
            now,
            report.was_queued,
            report.queued_at,
            report.queue_position,
            report.ping_sequence,
            loc_enc,
            loc_data,
        ),
    )

    # COALESCE: an old app build that doesn't send capture_armed (None) must
    # not wipe the stored state — the column keeps its last known value.
    conn.execute(
        "UPDATE devices SET last_seen=?, sentinel_score=?, capture_armed=COALESCE(?, capture_armed) WHERE id=?",
        (now, score, report.capture_armed, device_id),
    )


def _queue_auto_action(db, device_id: str, command: str):
    """Queue one geofence auto-action command (priority 1, poll delivery),
    deduplicated against an identical already-pending row.

    The exit transition fires exactly once (last_inside is persisted below),
    but the device may keep pinging from outside the zone — without this
    guard each ping would queue another capture/siren until the first one
    expired.
    """
    pending = db.execute(
        "SELECT 1 FROM commands WHERE device_id=? AND command=? AND status='pending' LIMIT 1",
        (device_id, command),
    ).fetchone()
    if pending:
        return
    now = datetime.now(timezone.utc).isoformat()
    # Mirror issue_command's expiry policy: the alarm is sensitive (5 min),
    # the evidence captures get the standard 30-minute window.
    expires = (datetime.now(timezone.utc) + timedelta(minutes=5 if command == "alarm" else 30)).isoformat()
    db.execute(
        "INSERT INTO commands (device_id, command, params, status, priority, issued_at, expires_at, delivery_channel) "
        "VALUES (?, ?, '', 'pending', 1, ?, ?, 'poll')",
        (device_id, command, now, expires),
    )


def _alert_recent(device_id: str, alert_type: str, minutes: int = 10) -> bool:
    """True when an alert of the given type was already logged for this device
    in the last `minutes` minutes. Shared by the location and heartbeat paths
    so one incident (including queued/offline replays of the same flag) = one
    always-deliver alert.

    Reads through the CURRENT database module (resolved at call time) rather
    than the request connection: alert_engine.send_all resolves
    `from database import get_db_context` at call time too, so under
    full-suite test eviction it writes rows to a DIFFERENT module than the
    one the request's `db` came from. Reading the same module send_all
    writes keeps the dedup truthful (same convention as test_alert_settings
    seeding the current module). Single-process production has one module,
    so the two are identical there.

    sent_at is written by SQLite as CURRENT_TIMESTAMP (UTC, 'YYYY-MM-DD
    HH:MM:SS') — comparing against datetime('now', '-N minutes') is
    apples-to-apples UTC.
    """
    import database as _current_db

    with _current_db.get_db_context() as conn:
        recent = conn.execute(
            "SELECT 1 FROM alerts WHERE device_id=? AND alert_type=? "
            "AND datetime(sent_at) > datetime('now', ?) LIMIT 1",
            (device_id, alert_type, f"-{minutes} minutes"),
        ).fetchone()
    return recent is not None


def _sim_changed_alert_recent(device_id: str) -> bool:
    """True when a sim_changed alert was already logged for this device in the
    last 10 minutes. Shared by the location and heartbeat paths so one incident
    (including queued/offline replays of the same flag) = one always-deliver
    alert."""
    return _alert_recent(device_id, "sim_changed")


def _failed_unlock_capture_recent(db, device_id: str, minutes: int = 5) -> bool:
    """True when a failed-unlock capture pair was already queued for this
    device within the last `minutes` minutes.

    The on-device EVIDENCE window is ~5 minutes, so one pair per window
    keeps evidence flowing while a locked device keeps pinging — without the
    continuous re-queue flood. G1-9 (found in the real-theft field test): a
    photo/audio pair re-queued every ~15s while the count stayed above the
    threshold, and the resulting request burst from one mobile IP got the
    device's network path to the server blocked (last_seen frozen, uploads
    failing with HTTP -1 / read timeouts) — exactly the moment evidence
    MUST upload.

    Reads through the REQUEST connection (`db`) — the same connection that
    inserts the commands — so the check is exact and has none of the
    module-eviction ambiguity of a separately-resolved connection.
    """
    recent = db.execute(
        "SELECT 1 FROM commands WHERE device_id=? "
        "AND command IN ('capture_photo_front', 'capture_audio') "
        "AND datetime(issued_at) > datetime('now', ?) LIMIT 1",
        (device_id, f"-{minutes} minutes"),
    ).fetchone()
    return recent is not None


def _queue_failed_unlock_reaction(db, device_id: str) -> None:
    """Queue the "theftie" evidence pair (front photo + ambient audio) for a
    device whose failed-unlock count crossed the threshold.

    Reuses the geofence auto-action machinery: priority-1 poll commands,
    deduplicated against identical already-pending rows so a device that
    keeps pinging from a locked screen never piles up repeats — and bounded
    to ONE pair per EVIDENCE window (G1-9) so the reaction can never flood
    the device's network path (see _failed_unlock_capture_recent).
    """
    if _failed_unlock_capture_recent(db, device_id):
        return
    _queue_auto_action(db, device_id, "capture_photo_front")
    _queue_auto_action(db, device_id, "capture_audio")


@router.post("/api/device/location")
async def post_location(
    report: TelemetryPing,
    db: sqlite3.Connection = Depends(get_db),
    device_id: str = Depends(get_current_device_or_key),
):
    """Receive telemetry ping from device."""
    if report.device_id != device_id:
        raise HTTPException(status_code=403, detail="Device ID mismatch")

    if not check_location_rate_limit(device_id):
        raise HTTPException(status_code=429, detail="Rate limit exceeded")

    now = datetime.now(timezone.utc).isoformat()

    # Validate GPS coordinates before processing - reject obviously invalid
    # fixes (ocean, Antarctica, garbage values) but log them for diagnostics.
    loc_valid, loc_reason, loc_warning = validate_location_report(
        report.lat, report.lng, report.accuracy_horizontal, report.provider
    )
    if not loc_valid:
        logger.warning(
            "Rejecting invalid location report",
            extra={"extra_data": {"device_id": device_id, "reason": loc_reason}},
        )
        log_audit("invalid_location", actor=device_id, details=loc_reason)
        # Still return success to avoid tipping off the device, but don't
        # persist the garbage coordinates.
        commands = db.execute(
            "SELECT id, command, params, priority FROM commands"
            " WHERE device_id=? AND status='pending'"
            " ORDER BY priority",
            (device_id,),
        ).fetchall()
        return {"status": "ok", "commands_pending": len(commands), "server_time": now}

    is_valid, reason = sentinel.validate_report(report, None)
    if not is_valid:
        log_audit("invalid_location_report", actor=device_id, details=reason)
    ts = report.device_timestamp or now

    history = db.execute(
        "SELECT * FROM locations WHERE device_id=? ORDER BY server_timestamp DESC LIMIT 10",
        (device_id,),
    ).fetchall()

    # Sentinel's haversine/geofence math runs on REAL coordinates — decrypt
    # any encrypted history rows before compute_score (encrypted rows carry
    # 0.0 placeholders in lat/lng; passing those through would poison the
    # movement/velocity signals).
    history_dicts = []
    for h in history:
        hd = dict(h)
        hd["lat"], hd["lng"] = decrypt_location_row(hd)
        history_dicts.append(hd)
    score, threat_level, anomalies = sentinel.compute_score(report, history_dicts)

    # Batched path (opt-in, MT_WRITE_BATCH_MS>0): defer the INSERT + device
    # UPDATE to this worker's write queue so the request NEVER contends for
    # SQLite's single-writer lock (measured: sync commits cap the whole server
    # at ~370 req/s with 3s p50 latency — batching collapses N commits into one
    # and makes the request path a read-only WAL reader). The device row's
    # last_seen lands within one flush window (~250ms); the dashboard is not
    # delayed because the WebSocket broadcast below carries the fresh fix+score
    # immediately. If the queue is enabled but not yet started, enqueue_write
    # returns False and we fall back to the synchronous path — a write is
    # never silently dropped.
    if write_queue_enabled() and enqueue_write(
        partial(
            _persist_location,
            device_id=device_id,
            report=report,
            score=score,
            threat_level=threat_level,
            anomalies=anomalies,
            now=now,
            ts=ts,
        )
    ):
        # unarchive stays on the request connection: it is a no-op unless the
        # device was archived, and when it writes it must be durable now.
        unarchive_device(db, device_id)
        db.commit()
    else:
        _persist_location(
            db,
            device_id=device_id,
            report=report,
            score=score,
            threat_level=threat_level,
            anomalies=anomalies,
            now=now,
            ts=ts,
        )
        # Fresh telemetry un-archives a device that came back online.
        unarchive_device(db, device_id)
        db.commit()

    if score >= settings.THEFT_SCORE_THRESHOLD:
        sentinel.auto_activate_theft_mode(device_id, score)
        await alert_engine.send_all(
            device_id,
            "theft_detected",
            {"location": f"{report.lat},{report.lng}", "time": now, "score": score},
        )

    # SIM change fires its OWN always-deliver alert the instant it is
    # reported — the owner must know a different SIM was inserted even when
    # the theft score has not accumulated to the confirmation threshold
    # (sim_changed alone scores 35/80). The device flags the change exactly
    # once; the 10-minute dedup also absorbs queued/offline replays so one
    # incident = one alert (tradeoff: two GENUINE swaps within 10 minutes are
    # coalesced — the owner is still alerted to the first, and the SIM
    # fingerprint is re-baselined on-device).
    if report.sim_changed and not _sim_changed_alert_recent(device_id):
        await alert_engine.send_all(
            device_id,
            "sim_changed",
            {"location": f"{report.lat},{report.lng}", "time": now},
        )

    # Failed-unlock "theftie" reaction (COMPETITOR_AUDIT P1 #4): repeated
    # failed unlock attempts strongly suggest a stranger in possession, and
    # the owner must know NOW while the device is still with the thief.
    # Sentinel already scored the signal above (+20, if it crossed the
    # threshold); here we queue the evidence pair (front photo + ambient
    # audio — the same commands geofence exits use) and fire an
    # always-deliver alert. Deduped: _queue_failed_unlock_reaction skips
    # identical already-pending commands, and the 10-minute alert window
    # absorbs queued/offline replays so one incident = one alert (same
    # tradeoff as sim_changed).
    if report.failed_unlock_count is not None and report.failed_unlock_count >= settings.FAILED_UNLOCK_THRESHOLD:
        _queue_failed_unlock_reaction(db, device_id)
        # Commit BEFORE send_all (same nested-write hazard documented on the
        # geofence path below: send_all opens its own connection).
        db.commit()
        if not _alert_recent(device_id, "failed_unlock_attempts"):
            await alert_engine.send_all(
                device_id,
                "failed_unlock_attempts",
                {
                    "attempts": report.failed_unlock_count,
                    "location": f"{report.lat},{report.lng}",
                    "time": now,
                },
            )

    geofences = db.execute("SELECT * FROM geofences WHERE device_id=? AND active=1", (device_id,)).fetchall()

    if geofences:
        triggered = sentinel.check_geofences(report, [dict(g) for g in geofences])
        # Collect the exits that need an alert so the alert fires AFTER the
        # transaction below is committed — send_all() opens its OWN connection
        # and writes alert rows; calling it while this request connection still
        # holds uncommitted writes makes it block on our lock and raise
        # "database is locked" after busy_timeout (same hazard the heartbeat
        # path documents — see post_heartbeat's "Commit BEFORE any nested
        # writes" note).
        exits_to_alert = []
        for event in triggered:
            # Persist the per-zone inside/outside state so the SAME transition
            # is never re-reported on later pings. This write is what makes
            # check_geofences' was_inside truthful: without it every ping saw
            # was_inside=False and 'exited' events (and the exit alert) could
            # never fire — dead code in production (v1.5 fix).
            db.execute(
                "UPDATE geofences SET last_inside=? WHERE id=?",
                (1 if event["event"] == "entered" else 0, event["geofence_id"]),
            )
            if event["event"] != "exited":
                continue
            # Geofence exit alert — fires for SAFE-ZONE exits (the product
            # meaning: "your device left the safe zone"). The template says
            # 'safe zone' but the old condition checked `not is_safe_zone`, so
            # exiting HOME never alerted while exiting a restricted zone did —
            # inverted vs. the product intent (v1.5 fix).
            if event["is_safe_zone"]:
                exits_to_alert.append(event)
            # Per-zone auto-actions (owner-set policy): react on the device
            # itself, regardless of safe/restricted classification (the owner
            # chose this reaction for THIS zone). 'capture' = front-camera
            # photo + ambient audio (the theft-mode evidence pair); 'siren' =
            # max-volume alarm. Deduped against already-pending identical
            # commands so one exit never piles up repeats.
            action = event.get("auto_action")
            if action == "capture":
                _queue_auto_action(db, device_id, "capture_photo_front")
                _queue_auto_action(db, device_id, "capture_audio")
            elif action == "siren":
                _queue_auto_action(db, device_id, "alarm")
        db.commit()
        for event in exits_to_alert:
            await alert_engine.send_all(
                device_id,
                "geofence_exit",
                {
                    "zone_name": event["name"],
                    "location": f"{report.lat},{report.lng}",
                    "time": now,
                },
            )

    # Accuracy is a core part of a tracking UI ("±12m" vs "±500m" changes
    # what the operator trusts). The dashboard's live map/panel reads
    # accuracy_horizontal — this broadcast used to omit it (and
    # provider/bearing/confidence), so the real-time feed always rendered
    # "±?m" even though the device reported the fused Kalman accuracy on
    # every ping.
    await broadcast_to_dashboards(
        {
            "type": "location",
            "data": {
                "device_id": device_id,
                "lat": report.lat,
                "lng": report.lng,
                "speed": report.speed,
                "battery": report.battery_percent,
                "sentinel_score": score,
                "threat_level": threat_level,
                "timestamp": now,
                "accuracy_horizontal": report.accuracy_horizontal,
                "provider": report.provider,
                "bearing": report.bearing,
                "confidence_level": report.confidence_level,
            },
        }
    )

    commands = db.execute(
        "SELECT id, command, params, priority FROM commands WHERE device_id=? AND status='pending' ORDER BY priority",
        (device_id,),
    ).fetchall()

    return {
        "status": "ok",
        "commands_pending": len(commands),
        "server_time": now,
    }


