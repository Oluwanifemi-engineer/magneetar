# ─── Media Uploads ───────────────────────────────────────────────────────────


@router.post("/api/device/media")
async def post_media(
    report: MediaReport,
    db: sqlite3.Connection = Depends(get_db),
    device_id: str = Depends(get_current_device_or_key),
):
    """Upload media (photo/audio) from device."""
    if report.device_id != device_id:
        raise HTTPException(status_code=403, detail="Device ID mismatch")

    if not check_media_rate_limit(device_id):
        raise HTTPException(status_code=429, detail="Media upload rate limit exceeded")

    now = datetime.now(timezone.utc).isoformat()
    ts = report.timestamp or now

    data = base64.b64decode(report.data_b64)
    sha256_hash = hashlib.sha256(data).hexdigest()

    case = db.execute(
        "SELECT id FROM evidence_cases WHERE device_id=? AND status='active' ORDER BY created_at DESC LIMIT 1",
        (device_id,),
    ).fetchone()

    case_id = case["id"] if case else None

    db.execute(
        """INSERT INTO media (device_id, type, data_b64, lat, lng, timestamp,
           evidence_case_id, sha256_hash)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
        (
            device_id,
            report.type,
            report.data_b64,
            report.lat,
            report.lng,
            ts,
            case_id,
            sha256_hash,
        ),
    )
    db.commit()

    media_id = db.execute("SELECT last_insert_rowid()").fetchone()[0]

    if case_id:
        evidence_builder.add_media_to_case(case_id, report.type, report.data_b64)

    await broadcast_to_dashboards(
        {
            "type": "media",
            "data": {
                "device_id": device_id,
                "media_id": media_id,
                "type": report.type,
                "timestamp": ts,
            },
        }
    )

    return {
        "status": "ok",
        "media_id": media_id,
        "evidence_case_id": case_id,
    }


# ─── Commands (Device Polling) ───────────────────────────────────────────────


@router.get("/api/device/commands/{device_id}")
async def get_device_commands(
    device_id: str,
    db: sqlite3.Connection = Depends(get_db),
    token_device_id: str = Depends(get_current_device_or_key),
):
    """Poll for pending commands."""
    if device_id != token_device_id:
        raise HTTPException(status_code=403, detail="Device ID mismatch")

    if not check_command_poll_rate_limit(device_id):
        raise HTTPException(status_code=429, detail="Command poll rate limit exceeded")

    rows = db.execute(
        """SELECT id, command, params, priority
           FROM commands
           WHERE device_id=? AND status='pending'
           AND (expires_at IS NULL OR datetime(expires_at) > datetime('now'))
           ORDER BY priority ASC""",
        (device_id,),
    ).fetchall()

    return {"commands": [dict(r) for r in rows]}


@router.post("/api/device/commands/{command_id}/ack")
async def ack_command(
    command_id: int,
    ack: CommandAck,
    db: sqlite3.Connection = Depends(get_db),
    device_id: str = Depends(get_current_device_or_key),
):
    """Acknowledge command execution."""
    now = datetime.now(timezone.utc).isoformat()

    db.execute(
        "UPDATE commands SET status=?, executed_at=? WHERE id=? AND device_id=?",
        (ack.status, now, command_id, device_id),
    )
    db.commit()

    await broadcast_to_dashboards(
        {
            "type": "command_ack",
            "data": {
                "command_id": command_id,
                "device_id": device_id,
                "status": ack.status,
            },
        }
    )

    return {"status": "ok"}


# ─── Heartbeat ───────────────────────────────────────────────────────────────


@router.post("/api/device/heartbeat")
async def post_heartbeat(
    hb: HeartbeatPacket,
    db: sqlite3.Connection = Depends(get_db),
    device_id: str = Depends(get_current_device_or_key),
):
    """Receive heartbeat from device."""
    if hb.device_id != device_id:
        raise HTTPException(status_code=403, detail="Device ID mismatch")

    if not check_heartbeat_rate_limit(device_id):
        raise HTTPException(status_code=429, detail="Heartbeat rate limit exceeded")

    now = datetime.now(timezone.utc).isoformat()

    db.execute(
        """INSERT INTO heartbeats (device_id, timestamp, battery_percent, is_charging,
           network_type, device_admin_active, sim_hash, app_version, pending_evidence_count)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        (
            device_id,
            now,
            hb.battery_percent,
            hb.is_charging,
            hb.network_type,
            hb.device_admin_active,
            hb.sim_hash,
            hb.app_version,
            hb.pending_evidence_count,
        ),
    )

    # COALESCE keeps the last known armed state when an old app build omits
    # the field (None) — a fresh report never wipes it to NULL.
    db.execute(
        "UPDATE devices SET last_seen=?, app_version=?, capture_armed=COALESCE(?, capture_armed) WHERE id=?",
        (now, hb.app_version, hb.capture_armed, device_id),
    )

    # ── Commit BEFORE any nested writes ──────────────────────────────────────
    # auto_activate_theft_mode() and log_audit() open their OWN sqlite
    # connection. Calling them while this request's write transaction is still
    # open makes the nested writer block on our uncommitted writes and raise
    # "database is locked" after busy_timeout — the resulting 500 rolls back
    # the heartbeat's last_seen update, so the dashboard freezes the device's
    # "last seen" at its previous time even though the phone is alive.
    db.commit()

    # Device admin being disabled is a strong theft signal (weight 40 in
    # sentinel.THEFT_SIGNALS), but it must NOT auto-activate stolen mode from a
    # bare heartbeat: escalation is reserved for the location path's
    # confirmation-gated score (>= THEFT_SCORE_THRESHOLD). Persist the elevated
    # score so the dashboard reflects the signal; the location path still owns
    # escalation to stolen.
    if hb.device_admin_active is False:
        db.execute(
            "UPDATE devices SET sentinel_score = MAX(sentinel_score, 40) WHERE id=?",
            (device_id,),
        )
        db.commit()

    device = db.execute("SELECT operating_mode FROM devices WHERE id=?", (device_id,)).fetchone()

    return {
        "status": "ok",
        "operating_mode": device["operating_mode"] if device else "normal",
        "server_time": now,
    }


